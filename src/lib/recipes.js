/** 이름으로 재료 하나를 만든다. 가격표에 없는 이름은 데이터 실수이므로 바로 알린다. */
function ing(name) {
  const price = PRICES[name]
  if (typeof price !== 'number') {
    throw new Error(`recipes.js: '${name}' 의 가격이 가격표에 없습니다.`)
  }
  return { name, price }
}

