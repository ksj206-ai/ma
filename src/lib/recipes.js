/** id 로 요리 하나를 찾는다. */
export function getRecipe(recipeId) {
  return RECIPES.find((recipe) => recipe.id === recipeId) || null
}

/** 금액 표시: 26100 -> "26,100원" */
export function formatWon(amount) {
  return `${Number(amount).toLocaleString('ko-KR')}원`
}
